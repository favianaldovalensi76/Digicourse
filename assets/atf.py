# Membuat variabel a dan b
a = 10  # nilai bertipe data integer
b = 3   # nilai bertipe data integer

# Hasil pembagian tipe data integer
hasil_pembagian_integer = a // b  # Pembagian tanpa sisa
print("Hasil pembagian integer:", hasil_pembagian_integer)

# Hasil pembagian tipe data float
hasil_pembagian_float = a / b  # Pembagian dengan hasil float
print("Hasil pembagian float:", hasil_pembagian_float)
